const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const api = require("./core.js");
const destination = process.argv[2];
if (!destination) throw new Error("Usage: node demo.cjs NEW_OUTPUT_DIRECTORY");
fs.mkdirSync(destination, {recursive: false});
const table = api.parseCSV(fs.readFileSync(path.join(__dirname, "example.csv"), "utf8"));
const rows = api.makeRows(table, api.suggestMapping(table.headers));
const before = api.evaluate(rows, "ymd");
assert.equal(before.filter(row => row.status === "Held").length, 3);
assert.throws(() => api.exportCSV(rows, "ymd", "checked"));
rows[2].values.out1 = "17:00";
rows[3].excluded = true;
rows[3].note = "Repeated line confirmed against the source";
const after = api.evaluate(rows, "ymd");
assert.equal(after.filter(row => row.status === "Held").length, 0);
assert.equal(after.reduce((sum, row) => sum + (row.minutes || 0), 0), 1665);
fs.writeFileSync(path.join(destination, "checked.csv"), api.exportCSV(rows, "ymd", "checked"), {flag: "wx"});
fs.writeFileSync(path.join(destination, "review.csv"), api.exportCSV(rows, "ymd", "review"), {flag: "wx"});
const readback = api.parseCSV(fs.readFileSync(path.join(destination, "checked.csv"), "utf8"));
assert.equal(readback.records.length, 4);
console.log(JSON.stringify({status: "PASS", beforeHeld: 3, afterHeld: 0, excluded: 1, checkedRows: 4, minutes: 1665, hours: 27.75, scope: "Core journey and persisted CSV readback. Browser verification is separate."}));
